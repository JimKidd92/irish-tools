// Merges agent-written surname content (src/data/_gen/surnames-*.json) into:
//   src/data/surnamesRich.generated.js  — SURNAME_RICH (pronunciation/history/variants/bearers)
//   src/data/surnamesExtra.generated.js — EXTRA_SURNAMES (base fields for NEW names)
// Idempotent. Run: node scripts/assemble-surnames.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { SURNAMES } from '../src/data/surnames.js'
import { EXTRA_SURNAMES as PREV_EXTRA } from '../src/data/surnamesExtra.generated.js'

const GEN = 'src/data/_gen'
// SURNAMES already includes previous extras; base = everything minus those, and
// we re-seed the extras so reruns keep them (idempotent).
const prevExtraNames = new Set(PREV_EXTRA.map((s) => s.name.toLowerCase()))
const baseNames = new Set(SURNAMES.map((s) => s.name.toLowerCase()).filter((n) => !prevExtraNames.has(n)))

const rich = {}
const extra = [...PREV_EXTRA]
const extraSeen = new Set(prevExtraNames)
const problems = []

const validRich = (e) =>
  Array.isArray(e.history) && e.history.length >= 1 && e.history.every((p) => typeof p === 'string' && p.length > 60) &&
  Array.isArray(e.variants) && e.variants.every((v) => typeof v === 'string') &&
  Array.isArray(e.bearers) && e.bearers.length >= 1 && e.bearers.every((b) => b.name && b.note) &&
  typeof e.pronunciation === 'string' && e.pronunciation.length > 3

for (const file of readdirSync(GEN).filter((f) => /^surnames-\d+\.json$/.test(f)).sort()) {
  let data
  try {
    data = JSON.parse(readFileSync(`${GEN}/${file}`, 'utf8'))
  } catch (e) {
    problems.push(`${file}: unparseable (${e.message})`)
    continue
  }
  for (const [name, entry] of Object.entries(data)) {
    if (!validRich(entry)) {
      problems.push(`${file}: ${name} failed rich validation`)
      continue
    }
    const isNew = Boolean(entry.new)
    const exists = baseNames.has(name.toLowerCase())
    if (isNew && exists) {
      // Agent added something we already have — keep the rich part only.
      rich[name] = pick(entry)
      continue
    }
    if (isNew) {
      if (!entry.irish || !entry.meaning || !entry.region) {
        problems.push(`${file}: new name ${name} missing base fields`)
        continue
      }
      const key = name.toLowerCase()
      if (extraSeen.has(key)) continue
      extraSeen.add(key)
      extra.push({ name, irish: entry.irish, meaning: entry.meaning, region: entry.region })
    } else if (!exists) {
      problems.push(`${file}: enrich target ${name} not in base list (skipped)`)
      continue
    }
    rich[name] = pick(entry)
  }
}

function pick(e) {
  return { pronunciation: e.pronunciation, history: e.history, variants: e.variants, bearers: e.bearers }
}

extra.sort((a, b) => a.name.localeCompare(b.name))

writeFileSync(
  'src/data/surnamesRich.generated.js',
  '// Generated by scripts/assemble-surnames.mjs — rich per-surname content\n' +
    '// (pronunciation, history, variants, notable bearers). Do not edit by hand.\n' +
    'export const SURNAME_RICH = ' + JSON.stringify(rich, null, 1) + '\n',
)
writeFileSync(
  'src/data/surnamesExtra.generated.js',
  '// Generated by scripts/assemble-surnames.mjs — additional surnames beyond the\n' +
    '// hand-written base list. Do not edit by hand.\n' +
    'export const EXTRA_SURNAMES = ' + JSON.stringify(extra, null, 1) + '\n',
)

console.log(`rich entries: ${Object.keys(rich).length} | extra surnames: ${extra.length} | total surnames: ${baseNames.size + extra.length}`)
const richLower = new Set(Object.keys(rich).map((r) => r.toLowerCase()))
console.log(`base without rich yet: ${[...baseNames].filter((n) => !richLower.has(n)).length}`)
if (problems.length) console.log('PROBLEMS:\n  ' + problems.slice(0, 20).join('\n  ') + (problems.length > 20 ? `\n  …+${problems.length - 20} more` : ''))
